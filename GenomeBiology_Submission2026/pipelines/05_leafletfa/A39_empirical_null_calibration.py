#!/usr/bin/env python
"""A39: can TV be calibrated against a null built from the variational posterior? NO.

Run: python A39_empirical_null_calibration.py --dir <DS_CALIBRATION>

This is a NEGATIVE result, kept because it identifies the blocker precisely.

The idea
--------
A38 showed the miscalibration comes from TV being positively biased under the null while being
compared against a fixed delta = 0.10. The obvious fix is to compare TV against its own null
distribution instead. For a truly null ATSE the true Delta_j is exactly 0 -- Delta_j =
(phibar_A - phibar_B) . psi_:,j, and if psi_kj is identical across programs then Delta_j = 0
because both phibar are simplices and their difference sums to zero. So all of a null ATSE's TV
is psi estimation noise amplified by |dphi|_1.

That suggests a parametric bootstrap: keep the observed dphi, give every program the SAME logit
centre (the across-program mean) while keeping its own posterior scale, and read off the null:

    psi_kj^null = sigmoid( mean_k(loc_kj) + scale_kj * eps )

What happened
-------------
It is badly anti-conservative -- worse than the fixed threshold it was meant to replace:

    effect 0.25, nominal 0.05:   fixed delta FDP 0.156 / power 0.41
                                 empirical null FDP 0.579 / power 0.77
    effect 0.50, nominal 0.05:   fixed delta FDP 0.201 / power 0.76
                                 empirical null FDP 0.364 / power 0.84

Why
---
The constructed null is 1.9x too tight: observed TV on truly null ATSEs has median 0.0170, the
constructed null has median 0.0087. The guide's own scale reproduces posterior SAMPLING noise
only, while the null TV is generated by psi_loc differing across programs through ESTIMATION
error, which mean-field VI does not represent.

How much too narrow -- restricted to junctions that are truly null, which is the honest
comparison, since for a genuinely differential junction psi_loc SHOULD differ across programs:

                              across-program sd(psi_loc)   q(psi) scale   ratio
    effect 0.25, all             0.2930                      0.1076       2.72x
    effect 0.25, TRUE NULLS      0.1846                      0.1119       1.65x
    effect 0.50, all             0.2538                      0.0967       2.62x
    effect 0.50, TRUE NULLS      0.1303                      0.1023       1.27x

Take the true-null rows: the posterior is 1.3-1.7x too narrow, not 2.7x. The all-junctions
figure is inflated by the 31% of junctions that are genuinely differential and is the wrong
number to quote.

That reframes the Dirichlet-multinomial rather than excusing it. The DM widens q(psi) by 1.29x
(`experiments/dirichlet_multinomial/04_posterior_width_in_model.py`), which already covers most
of a 1.3-1.7x shortfall -- so width is close to being handled, and yet A36 still shows FDP
1.4-2.4x over nominal. The residual is therefore NOT mainly width. It is the bias A38 identified:
TV compared against a fixed delta = 0.10 when null TV sits at 0.017-0.025 and the median TRUE
positive sits at 0.096. Widening a posterior cannot fix a threshold that is in the wrong place.

What this means for the plan
----------------------------
A structured guide (AutoLowRankMultivariateNormal) is worth LESS than the raw 2.7x suggested,
because most of the width gap is already closed by the DM. The blocking problem is the absolute
delta threshold. The fix is a null built by resampling the DATA -- permutation plus a refit, or
at minimum a phi E-step -- not from the fitted posterior. `DS_CALIBRATION/null_tv_*.npz` already
holds exactly that for the real atlas (donor-split null), so the route exists; it costs compute
rather than being free.

Truth labels are used only to SCORE the result, never to build the null, so the procedure under
test is one that could actually be shipped.
"""

import argparse
import glob
import os

import numpy as np


def bh(p):
    """Benjamini-Hochberg adjusted p-values."""
    n = len(p)
    o = np.argsort(p)
    q = np.empty(n)
    q[o] = np.minimum.accumulate((p[o] * n / np.arange(1, n + 1))[::-1])[::-1]
    return np.clip(q, 0, 1)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dir", required=True)
    ap.add_argument("--sim", default="/gpfs/commons/groups/knowles_lab/Karin/"
                                     "Leaflet-analysis-WD/SIMULATION")
    ap.add_argument("--num-null", type=int, default=500)
    ap.add_argument("--delta", type=float, default=0.10)
    ap.add_argument("--alphas", type=float, nargs="+", default=[0.01, 0.02, 0.05, 0.10, 0.20])
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    import h5py
    import scipy.sparse as sp  # noqa: F401  (h5ad reader needs it in some paths)

    for eff in ("0.25", "0.5"):
        tagbase = f"sim_heart_K5_binom_eff{eff}_frac0.3_seed0"
        fit_p = os.path.join(args.dir, f"simfit_{tagbase}.npz")
        score_fs = sorted(glob.glob(os.path.join(args.dir, f"simscores_{tagbase}_*.npz")))
        if not (os.path.exists(fit_p) and score_fs):
            continue
        z = np.load(fit_p)
        phi, loc, scale = z["phi"], z["psi_loc"], z["psi_scale"]
        K, J = loc.shape

        # junction -> ATSE, and the true program of each cell, from the simulation itself
        with h5py.File(os.path.join(args.sim, f"{tagbase}.h5ad"), "r") as f:
            node = f["var"]["event_id"]
            if isinstance(node, h5py.Group):
                cats = np.array([x.decode() if isinstance(x, bytes) else x
                                 for x in node["categories"][:]])
                ev = cats[node["codes"][:]]
            else:
                ev = np.array([x.decode() if isinstance(x, bytes) else x for x in node[:]])
            pnode = f["obs"]["true_program"]
            if isinstance(pnode, h5py.Group):
                pcats = np.array([x.decode() if isinstance(x, bytes) else x
                                  for x in pnode["categories"][:]])
                prog = pcats[pnode["codes"][:]]
            else:
                prog = np.array([x.decode() if isinstance(x, bytes) else x for x in pnode[:]])
        # true_program is stored as int64 in these files, while the contrast names parsed out of
        # the score filenames are strings. Comparing the two matches NOTHING and yields an empty
        # mean -> NaN dphi -> every ATSE significant, which looks like a spectacular result.
        prog = np.asarray(prog).astype(str)
        uq_ev, inv_ev = np.unique(ev, return_inverse=True)
        n_atse = len(uq_ev)

        rng = np.random.default_rng(args.seed)
        S = args.num_null

        def draw(centre):
            """centre [K, J] logit locations -> psi draws [S, K, J]."""
            eps = rng.standard_normal((S, K, J)).astype(np.float32)
            return 1.0 / (1.0 + np.exp(-(centre[None] + scale[None] * eps)))

        def tv(psi_s, dphi):
            d = np.einsum("k,skj->sj", dphi.astype(np.float32), psi_s)
            out = np.zeros((psi_s.shape[0], n_atse), dtype=np.float32)
            np.add.at(out.T, inv_ev, np.abs(d).T)
            return 0.5 * out

        # NULL centre: every program shares the across-program mean logit, keeping its own scale
        null_centre = np.repeat(loc.mean(axis=0, keepdims=True), K, axis=0)

        print("=" * 90)
        print(f"effect {eff}: TV thresholded at delta={args.delta}  vs  empirical p from the "
              f"per-ATSE null")
        print("=" * 90)
        # Restrict to truly null junctions: for a differential junction psi_loc SHOULD differ
        # across programs, so the all-junction spread is inflated by real signal.
        sdiff = _is_differential(os.path.join(args.sim, f"{tagbase}.h5ad"))
        for lab, msk in (("all junctions", np.ones(J, bool)), ("TRUE NULLS only", ~sdiff)):
            a_sd = float(np.median(loc[:, msk].std(0)))
            q_sd = float(np.median(scale[:, msk]))
            print(f"  DIAGNOSTIC [{lab:<15}] across-program sd(psi_loc) {a_sd:.4f}  "
                  f"q(psi) scale {q_sd:.4f}  -> {a_sd/max(q_sd,1e-9):.2f}x too narrow")
        print("    (quote the TRUE NULLS row; the other is inflated by real signal)")
        print(f"{'alpha':>6} | {'fixed-delta FDP':>16} {'power':>7} | "
              f"{'empirical-null FDP':>19} {'power':>7}")

        acc = {a: dict(fA=0, nA=0, tA=0, fB=0, nB=0, tB=0) for a in args.alphas}
        n_pos_total = 0
        for f in score_fs:
            sc = np.load(f)
            is_null = sc["is_null"]
            obs_tv = sc["tv"].astype(np.float64)
            prob = sc["prob_de"].astype(np.float64)
            n_pos_total += int((~is_null).sum())

            pq = os.path.basename(f).replace(f"simscores_{tagbase}_", "").replace(".npz", "")
            p_, q_ = pq.split("_vs_")
            m1, m2 = (prog == p_), (prog == q_)
            if m1.sum() == 0 or m2.sum() == 0:
                raise ValueError(f"contrast {p_} vs {q_}: matched {m1.sum()} and {m2.sum()} "
                                 f"cells. prog values look like {np.unique(prog)[:5]}")
            dphi = phi[m1].mean(0) - phi[m2].mean(0)

            null_tv = tv(draw(null_centre), dphi)                  # [S, n_atse]
            # empirical p: how often the null reaches the observed TV (add-one for a proper bound)
            pval = (1.0 + (null_tv >= obs_tv[None]).sum(0)) / (S + 1.0)
            q = bh(pval)

            for a in args.alphas:
                selA, _ = fdr_select(prob, a)
                acc[a]["fA"] += int((selA & is_null).sum()); acc[a]["nA"] += int(selA.sum())
                acc[a]["tA"] += int((selA & ~is_null).sum())
                selB = q <= a
                acc[a]["fB"] += int((selB & is_null).sum()); acc[a]["nB"] += int(selB.sum())
                acc[a]["tB"] += int((selB & ~is_null).sum())

        for a in args.alphas:
            d = acc[a]
            fdpA = d["fA"] / max(d["nA"], 1)
            fdpB = d["fB"] / max(d["nB"], 1)
            print(f"{a:>6.2f} | {fdpA:>16.4f} {d['tA']/max(n_pos_total,1):>7.4f} | "
                  f"{fdpB:>19.4f} {d['tB']/max(n_pos_total,1):>7.4f}")
        print()


def _is_differential(h5_path):
    """Per-junction truth flag from the simulation."""
    import h5py
    with h5py.File(h5_path, "r") as f:
        n = f["var"]["is_differential"]
        v = n["codes"][:] if isinstance(n, h5py.Group) else n[:]
    return np.asarray(v).astype(bool)


def fdr_select(prob, alpha):
    order = np.argsort(-prob)
    lfdr = 1.0 - prob[order]
    cum = np.cumsum(lfdr) / np.arange(1, len(lfdr) + 1)
    k = int(np.searchsorted(cum, alpha, side="right"))
    sel = np.zeros(len(prob), dtype=bool)
    sel[order[:k]] = True
    return sel, (cum[k - 1] if k else 0.0)


if __name__ == "__main__":
    main()

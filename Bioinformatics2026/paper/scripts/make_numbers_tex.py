#!/usr/bin/env python3
"""make_numbers_tex.py -- results ledger -> numbers.tex for the manuscript (Overleaf).

Reads paper_config.yaml `numbers:` (ledger path, Overleaf repo root) and `output_dir`. Writes one \\newcommand per ledger row
with status "final" (its `display` column, as quoted in the text) to <output_dir>/numbers.tex. Rows that are not final are
skipped and listed as comments, so the Overleaf fallback (\\providecommand) stays visible until the number exists.
Then copies numbers.tex into the Overleaf repo root if that folder is on this machine: copy only, never a commit.

Checks before writing: macro names are letters only and unique; every final row's source_md5 matches its file on disk, so a
number whose source file changed is refused until it is re-derived.

Usage:  python scripts/make_numbers_tex.py [--config <paper_config.yaml>] [--no-copy]
"""
import argparse
import csv
import hashlib
import os
import re
import shutil
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_CONFIG = os.path.join(HERE, "..", "paper_config.yaml")


def md5(path, block=1 << 20):
    h = hashlib.md5()
    with open(path, "rb") as fh:
        for b in iter(lambda: fh.read(block), b""):
            h.update(b)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=DEFAULT_CONFIG)
    ap.add_argument("--no-copy", action="store_true", help="write numbers.tex but do not copy it to the Overleaf repo")
    a = ap.parse_args()
    with open(a.config) as fh:
        cfg = yaml.safe_load(fh)
    nb = cfg["numbers"]
    ledger = nb["ledger"] if os.path.isabs(nb["ledger"]) else os.path.join(os.path.dirname(os.path.abspath(a.config)), nb["ledger"])
    with open(ledger) as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    names = [r["macro"] for r in rows]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        sys.exit(f"duplicate macro(s) in the ledger: {', '.join(dup)}")
    out = ["% numbers.tex: generated by Bioinformatics2026/paper/scripts/make_numbers_tex.py from ledger/results_ledger.tsv. Do not edit by hand."]
    skipped, stale = [], []
    for r in rows:
        if not re.fullmatch(r"[A-Za-z]+", r["macro"]):
            sys.exit(f"macro must be letters only: {r['macro']}")
        if r["status"] != "final":
            skipped.append(r["macro"])
            continue
        if os.path.exists(r["source_file"]) and md5(r["source_file"]) != r["source_md5"]:
            stale.append(r["macro"])
            continue
        out.append(f"\\newcommand{{\\{r['macro']}}}{{{r['display']}}}  % {r['description']} | {os.path.basename(r['source_file'])} | "
                   f"job {r['job_id']} | {r['record']}")
    if stale:
        sys.exit(f"source md5 changed for: {', '.join(stale)} (re-derive these numbers before writing numbers.tex)")
    out += [f"% not final (Overleaf fallback stays): {m}" for m in skipped]
    os.makedirs(cfg["output_dir"], exist_ok=True)
    dst_file = os.path.join(cfg["output_dir"], "numbers.tex")
    with open(dst_file, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"numbers.tex: {len(out) - 1 - len(skipped)} macros written to {dst_file}; {len(skipped)} pending: {', '.join(skipped)}")
    root = nb.get("overleaf_repo_root")
    if a.no_copy:
        return
    if root and os.path.isdir(root):
        shutil.copyfile(dst_file, os.path.join(root, "numbers.tex"))
        print(f"copied to {os.path.join(root, 'numbers.tex')} (not committed)")
    else:
        print(f"Overleaf repo root not found ({root}); numbers.tex not copied")


if __name__ == "__main__":
    main()
